void FLIR_VOSPI_PrintPacketDump(void)
{
    uint8_t i, b;

    terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, BOLD_FONT);
    printf("    --- Last %u VoSPI packets (first %u of %u bytes, oldest first) ---\n\r",
           (unsigned)FLIR_VOSPI_DUMP_PACKETS, (unsigned)FLIR_VOSPI_DUMP_BYTES,
           (unsigned)FLIR_VOSPI_PACKET_BYTES);

    terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, NORMAL_FONT);

    if (stats.packetsCaptured == 0)
    {
        terminalTextAttributes(RED_COLOR, BLACK_COLOR, NORMAL_FONT);
        printf("    No packets have been captured at all -- the RX DMA has never\n\r");
        printf("    completed a block. Look at SPI4/DMA, not at the framing:\n\r");
        printf("    'Peripheral Status? FLIR SPI' (is DMA RX ch2 enabled? SPIROV?).\n\r");
        terminalTextAttributesReset();
        return;
    }

    // Oldest first: dumpNext points at the slot that will be written next,
    // which is the oldest entry once the ring has wrapped.
    for (i = 0; i < FLIR_VOSPI_DUMP_PACKETS; i++)
    {
        const uint8_t *p = dumpRing[(dumpNext + i) % FLIR_VOSPI_DUMP_PACKETS];

        printf("    ");
        for (b = 0; b < FLIR_VOSPI_DUMP_BYTES; b++) printf("%02X ", (unsigned)p[b]);

        // Decode the 4-byte header: ID (2 bytes) + CRC (2 bytes).
        if (FLIR_VOSPI_IS_DISCARD(p[0]))
        {
            printf("  discard\n\r");
        }
        else
        {
            printf("  packet %u", (unsigned)p[1]);
            if (p[1] == 20u) printf(", segment %u", (unsigned)((p[0] >> 4) & 0x07u));
            printf("\n\r");
        }
    }

    printf("    Packets: %lu total, %lu discards (%lu with data)\n\r",
           (unsigned long)stats.packetsCaptured, (unsigned long)stats.discardPackets,
           (unsigned long)(stats.packetsCaptured - stats.discardPackets));

    // Point at the likely cause rather than leaving the hex to be eyeballed.
    if (stats.discardPackets == stats.packetsCaptured)
    {
        terminalTextAttributes(YELLOW_COLOR, BLACK_COLOR, NORMAL_FONT);
        printf("    Every packet is a discard. If the bytes above are all FF the\n\r");
        printf("    sensor is not driving MISO (SDI4/RD7) at all -- check /CS (RD1),\n\r");
        printf("    the SPI4 PPS input mapping, and that SCK4 is really clocking.\n\r");
        printf("    If they are real 0x0Fxx headers the link is fine and the sensor\n\r");
        printf("    is simply producing no video (a CCI configuration problem).\n\r");
    }

    terminalTextAttributesReset();
}

