// Places one completed segment's 60 payloads into the capture frame buffer,
// byte-swapping and masking each pixel to 14 bits. seg is 1..4.
static void FLIR_VOSPI_PlaceSegment(uint8_t seg)
{
    uint32_t k;

    stats.segmentsPlaced++;
    if (seg <= FLIR_VOSPI_SEGMENTS_PER_FRAME) stats.segmentsPlacedById[seg]++;

    for (k = 0; k < FLIR_VOSPI_PACKETS_PER_SEGMENT; k++)
    {
        const uint8_t *src = &segScratch[k * FLIR_VOSPI_PACKET_PAYLOAD_BYTES];
        // Two packets per 160-pixel row; even packet = left 80px, odd = right.
        uint32_t row = ((uint32_t)(seg - 1) * 30u) + (k / 2u);
        uint32_t colStart = (k & 1u) * 80u;
        volatile uint16_t *dst = &captureFrame[(row * FLIR_VOSPI_WIDTH_PX) + colStart];
        uint32_t i;

        for (i = 0; i < 80u; i++)
        {
            // Full 16 bits, NOT masked to 14. The captured stream shows pixel
            // words like 0x73E4 / 0x70AF / 0x7C01 -- this Lepton 3.5 is
            // radiometric and outputs TLinear: value = temperature in
            // centi-Kelvin (0x73E4 = 29668 = 296.68K = 23.5C, room ambient;
            // 0x7C01 = 317.45K = 44.3C). Masking to 0x3FFF happens to look
            // right today only because every value in -109C..+54.5C has the
            // same top two bits; anything hotter than 54.5C wrapped to black.
            dst[i] = (uint16_t)(((uint16_t)src[i * 2u] << 8) | src[(i * 2u) + 1u]);
        }
    }
}

// Flips the freshly filled capture buffer to be the ready buffer, and points
// capture at the other one.
static void FLIR_VOSPI_CompleteFrame(void)
{
    volatile uint16_t *justFilled = captureFrame;

    readyFrame = justFilled;
    captureFrame = (justFilled == (volatile uint16_t *)FLIR_VOSPI_FRAME_A_ADDRESS)
                 ? (volatile uint16_t *)FLIR_VOSPI_FRAME_B_ADDRESS
                 : (volatile uint16_t *)FLIR_VOSPI_FRAME_A_ADDRESS;
    frameReadyFlag = true;
    stats.framesCaptured++;
}

// Walks one completed block packet by packet and accumulates segments/frames.
// Runs in the RX DMA block-complete ISR(s); integer-only per the ISR
// conventions (IPL5 shadow register set). It runs ~106 times a second and has
// the ~9.4ms of the next block to finish -- ample even for segment placement.
static void FLIR_VOSPI_ParseBlock(const uint8_t *block)
{
    uint32_t k;
    uint32_t blankInBlock = 0;

    for (k = 0; k < FLIR_VOSPI_PACKETS_PER_BLOCK; k++)
    {
        const uint8_t *pkt = &block[k * FLIR_VOSPI_PACKET_BYTES];
        uint8_t hdr0 = pkt[0];
        uint8_t pnum = pkt[1];

        // Snapshot for "FLIR Packet Dump" before any classification.
        memcpy(dumpRing[dumpNext], pkt, FLIR_VOSPI_DUMP_BYTES);
        dumpNext = (uint8_t)((dumpNext + 1u) % FLIR_VOSPI_DUMP_PACKETS);
        stats.packetsCaptured++;

        // A packet whose whole 4-byte header is zero is not a packet at all --
        // it is a dead MISO line being clocked into the buffer. A real packet
        // 0 carries a CRC in bytes 2..3 that is essentially never 0x0000.
        //
        // This must come before the packet-0 handling below, because
        // 00 00 00 00 otherwise reads as a perfectly good packet 0: the
        // restart rule resets the sequence, the packet is accepted, the next
        // zero packet restarts again... and the stream of nothing is consumed
        // forever while lastProgressTicks keeps being petted, so no watchdog
        // ever fires. That is exactly how the display once froze with 73,235
        // "segment restarts" against 100,024 packets -- a permanent freeze
        // with every counter looking healthy.
        if ((hdr0 == 0u) && (pnum == 0u) && (pkt[2] == 0u) && (pkt[3] == 0u))
        {
            stats.blankPackets++;
            blankInBlock++;
            continue;
        }

        // Discard/idle packets carry no image data.
        if (FLIR_VOSPI_IS_DISCARD(hdr0))
        {
            stats.discardPackets++;
            continue;
        }

        // Seek the start of a segment before trusting anything.
        if (!haveSync)
        {
            if (pnum != 0)
            {
                continue;
            }
            haveSync = true;
            expectedPacket = 0;
        }

        // Packet 0 unambiguously starts a new segment, whatever we were
        // expecting next. The sensor truncates the segments it marks invalid
        // rather than always emitting all 60 packets, so "expected 37, got 0"
        // is a normal segment restart, not a framing break -- counting it as a
        // desync (and dropping the lock over it) cost roughly one lost frame
        // per invalid segment. The partial segment simply never gets placed.
        if ((pnum == 0u) && (expectedPacket != 0u))
        {
            stats.segmentRestarts++;
            expectedPacket = 0;
            currentSegment = 0;
        }

        if (pnum != expectedPacket)
        {
            // Always a soft recovery: re-hunt for a packet 0 while continuing
            // to clock, never the 200ms /CS window.
            //
            // The previous rule paid a hard resync for any break at a block
            // boundary, on the theory that bytes lost across the re-arm had
            // shifted the packet grid. That premise was wrong: losing a byte
            // leaves the RX block one short, so it never completes and shows
            // up as a STALL, not as a completed block with bad packet numbers.
            // A desync therefore never implies lost byte alignment, and paying
            // 200ms for one cost ~5s of every 6.3s of run time -- capture was
            // idle in the resync window ~80% of the time. Genuine misalignment
            // is still caught, by the no-progress watchdog in
            // FLIR_VOSPI_Tasks() escalating to the /CS window.
            stats.desyncCount++;

            // Bound the churn. A misaligned grid still produces occasional
            // false locks onto bytes that happen to look like packet 0, and
            // each one pets the stall watchdog -- so misalignment could
            // otherwise persist for many watchdog periods, desyncing over and
            // over without escalating. Repeated breaks with no complete
            // segment in between mean the grid really is wrong: pay for the
            // /CS window now and get it right. (Bail out of the whole block
            // -- Disarm has just reset every piece of parse state.)
            consecutiveDesyncs++;
            if (consecutiveDesyncs >= FLIR_VOSPI_MAX_DESYNC_RUN)
            {
                FLIR_VOSPI_RequestResync();
                return;
            }

            FLIR_VOSPI_ResetSync();
            continue;
        }

        // Accepted packet: pet the stall watchdog and extend the run.
        // maxPacketRun is the honest measure of how close capture is getting
        // -- 60 is one whole segment, 240 unbroken is a frame.
        lastProgressTicks = lastPacketTicks;
        packetRun++;
        if (packetRun > stats.maxPacketRun) stats.maxPacketRun = packetRun;

        memcpy(&segScratch[pnum * FLIR_VOSPI_PACKET_PAYLOAD_BYTES],
               &pkt[FLIR_VOSPI_PACKET_HEADER_BYTES],
               FLIR_VOSPI_PACKET_PAYLOAD_BYTES);

        // The segment number is only meaningful in packet 20.
        if (pnum == 20u)
        {
            uint8_t seg = (uint8_t)((hdr0 >> 4) & 0x07u);

            stats.segmentIdSeen[seg]++;

            if ((seg < 1u) || (seg > FLIR_VOSPI_SEGMENTS_PER_FRAME))
            {
                // Segment id 0 is the sensor saying "this segment is not
                // valid, throw it away" -- normal and frequent, not an error.
                //
                // What must NOT happen here is the old ResetSync(): the packet
                // stream is perfectly in sync, only this segment's contents
                // are unusable. Dropping the lock over it meant re-hunting for
                // packet 0 every time, and with ~half of all segments coming
                // through invalid, four good ones could never accumulate back
                // to back -- which is exactly why frames stayed at 0 while
                // every other counter looked healthy.
                stats.segmentErrors++;
                currentSegment = 0;   // unusable; the stream stays locked
            }
            else
            {
                currentSegment = seg;
            }
        }

        if (pnum == (FLIR_VOSPI_PACKETS_PER_SEGMENT - 1u))
        {
            // A whole segment arrived in sequence, so the packet grid is
            // definitely right -- clear the misalignment evidence.
            consecutiveDesyncs = 0;

            // Segment complete. Only assemble frames from segments seen in
            // order starting at segment 1, so a mid-frame lock-on doesn't
            // stitch a torn frame together.
            if (currentSegment == 0u)
            {
                // Unusable segment (id 0 at packet 20, or we locked on after
                // packet 20 and never saw the id). Do nothing at all: no
                // placement, and crucially segmentMask is LEFT ALONE.
                //
                // We read a 60-packet block every ~9.4ms while the sensor
                // produces a real segment only every ~28.75ms, so it answers
                // with an id-0 segment roughly two times out of three -- they
                // fall BETWEEN the valid segments of a single frame. Clearing
                // the mask here (as the first version of this branch did)
                // therefore wiped the frame between segment 1 and segment 2
                // every time, which is why only segment 1s were ever placed
                // and no continuation ever ran.
            }
            else if (currentSegment == 1u)
            {
                segmentMask = 0x02u;   // bit for segment 1
                FLIR_VOSPI_PlaceSegment(1u);
            }
            else if (segmentMask & (1u << (currentSegment - 1u)))
            {
                // Previous segment in the run was placed -> this continues it.
                segmentMask |= (1u << currentSegment);
                FLIR_VOSPI_PlaceSegment(currentSegment);

                if ((currentSegment == FLIR_VOSPI_SEGMENTS_PER_FRAME) &&
                    (segmentMask == 0x1Eu))   // segments 1,2,3,4 all placed
                {
                    FLIR_VOSPI_CompleteFrame();
                    segmentMask = 0;
                }
            }
            else
            {
                // Out-of-order segment: wait for the next segment 1.
                segmentMask = 0;
            }

            expectedPacket = 0;
            currentSegment = 0;
        }
        else
        {
            expectedPacket++;
        }
    }

    // A block that was entirely blank means the sensor has stopped driving
    // MISO altogether. Nothing in the parser can recover that; only making
    // the sensor restart its stream will, so take the /CS window rather than
    // clocking in more of nothing -- but only after a few in a row (see
    // FLIR_VOSPI_BLANK_BLOCK_RUN for why reacting to the first one livelocks).
    if (blankInBlock == FLIR_VOSPI_PACKETS_PER_BLOCK)
    {
        stats.blankBlocks++;
        blankBlockRun++;

        if (blankBlockRun >= FLIR_VOSPI_BLANK_BLOCK_RUN)
        {
            FLIR_VOSPI_RequestResync();
        }
    }
    else
    {
        blankBlockRun = 0;
    }
}

#if FLIR_VOSPI_USE_CHAINED_DMA

// RX block A (DCH2) complete. The partner channel is already capturing -- the
// hardware chain enabled it in the same cycle this block finished -- so the
// only work here is the parse, with a whole block time of deadline.
void __ISR(_DMA2_VECTOR, IPL5SRS) flirVospiDmaISR(void)
{
    lastPacketTicks = _CP0_GET_COUNT();
    consecutiveUnsticks = 0;   // a completed block proves the clock is running

    DCH2INTCLR = _DCH2INT_CHBCIF_MASK;
    clearInterruptFlag(dma_channel_2);

    FLIR_VOSPI_ParseBlock(vospiBlock[0]);
}

// RX block B (DCH3) complete -- mirror of the above.
void __ISR(_DMA3_VECTOR, IPL5SRS) flirVospiDmaBISR(void)
{
    lastPacketTicks = _CP0_GET_COUNT();
    consecutiveUnsticks = 0;

    DCH3INTCLR = _DCH3INT_CHBCIF_MASK;
    clearInterruptFlag(dma_channel_3);

    FLIR_VOSPI_ParseBlock(vospiBlock[1]);
}

#else

// DMA channel 2 block-complete: a whole block of FLIR_VOSPI_PACKETS_PER_BLOCK
// packets has been captured into vospiBlock. Re-arm, then parse.
void __ISR(_DMA2_VECTOR, IPL5SRS) flirVospiDmaISR(void)
{
    const uint8_t *block = vospiBlock[activeBlock];

    lastPacketTicks = _CP0_GET_COUNT();

    // Re-arm into the OTHER buffer first, so the sensor's clock resumes
    // immediately and the parse below happens while the DMA is already
    // refilling. The DMA needs ~9.4ms to fill a block; the parse takes tens of
    // microseconds, so the two never collide.
    activeBlock ^= 1u;
    FLIR_VOSPI_ArmBlock();

    FLIR_VOSPI_ParseBlock(block);
}

#endif

// VSYNC rising edge from the Lepton (GPIO3 -> RD0 -> INT1). Frame-timing tick;
// the capture itself is DMA-driven, so this only keeps a count for now.
//
// NOTE: the Lepton does NOT drive VSYNC out of GPIO3 by default -- it has to
// be switched on with the OEM GPIO-mode CCI command, which lives in a
// protected module (the 0x4000 command bit) that flir_cci.c does not implement
// and whose code is not confirmed against FLIR doc #110-0144-04. So a
// vsyncCount of 0 is expected and is NOT evidence of an interrupt problem;
// nothing in the capture path depends on it.
void __ISR(_EXTERNAL_1_VECTOR, IPL4SRS) flirVsyncISR(void)
{
    stats.vsyncCount++;
    clearInterruptFlag(external_interrupt_1);
}

static uint32_t FLIR_VOSPI_GetBusSpeed(void)
{
    return FLIR_VOSPI_PBCLK_HZ / (2u * ((uint32_t)SPI4BRG + 1u));
}

void FLIR_VOSPI_PrintStatus(void)
{
    // MCU-peripheral view only (the SPI4/DMA/INT1 register settings behind the
    // VoSPI capture). Lepton module state and capture statistics live in
    // FLIR_PrintStatus() ("FLIR Status?").
    terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, BOLD_FONT);
    printf("    --- FLIR VoSPI MCU Peripherals (SPI4 / DMA / INT1) ---\n\r");

    // SPI4 controller.
    if (SPI4CONbits.ON) terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, NORMAL_FONT);
    else terminalTextAttributes(RED_COLOR, BLACK_COLOR, NORMAL_FONT);
    printf("    SPI4 Module: %s\n\r", SPI4CONbits.ON ? "enabled" : "disabled");

    terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, NORMAL_FONT);
    printf("    SPI4 Mode: master=%u, mode 3 (CKP=%u CKE=%u SMP=%u), %u-bit\n\r",
           (unsigned)SPI4CONbits.MSTEN, (unsigned)SPI4CONbits.CKP,
           (unsigned)SPI4CONbits.CKE, (unsigned)SPI4CONbits.SMP,
           SPI4CONbits.MODE32 ? 32u : (SPI4CONbits.MODE16 ? 16u : 8u));
    printf("    SPI4BRG: %u -> %lu Hz (PBCLK2 %lu Hz)\n\r",
           (unsigned)SPI4BRG, (unsigned long)FLIR_VOSPI_GetBusSpeed(),
           (unsigned long)FLIR_VOSPI_PBCLK_HZ);
    printf("    Enhanced buffer: %u  STXISEL=%u  SRXISEL=%u\n\r",
           (unsigned)SPI4CONbits.ENHBUF, (unsigned)SPI4CONbits.STXISEL,
           (unsigned)SPI4CONbits.SRXISEL);

    if (SPI4STATbits.SPIROV) terminalTextAttributes(RED_COLOR, BLACK_COLOR, NORMAL_FONT);
    else terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, NORMAL_FONT);
    printf("    SPI4 receive overflow: %s\n\r", SPI4STATbits.SPIROV ? "occurred" : "none");

    // DMA channels.
    terminalTextAttributes(GREEN_COLOR, BLACK_COLOR, NORMAL_FONT);
#if FLIR_VOSPI_USE_CHAINED_DMA
    printf("    Chained-DMA capture (RX hardware ping-pong, TX free-running CHAEN)\n\r");
    printf("    DMA RX A/B (ch2/ch3): %s/%s  CHSIRQ=%u(SPI4RX)  block=%uB\n\r",
           DCH2CONbits.CHEN ? "enabled" : "disabled",
           DCH3CONbits.CHEN ? "enabled" : "disabled",
           (unsigned)DCH2ECONbits.CHSIRQ, (unsigned)DCH2DSIZ);
    printf("    DMA TX (ch4, CHAEN=%u): %s  CHSIRQ=%u(SPI4TX)  block=%uB\n\r",
           (unsigned)DCH4CONbits.CHAEN,
           DCH4CONbits.CHEN ? "enabled" : "disabled",
           (unsigned)DCH4ECONbits.CHSIRQ, (unsigned)DCH4SSIZ);
#else
    printf("    DMA RX (ch2): %s  CHSIRQ=%u(SPI4RX)  cell=%uB  block=%uB\n\r",
           DCH2CONbits.CHEN ? "enabled" : "disabled", (unsigned)DCH2ECONbits.CHSIRQ,
           (unsigned)DCH2CSIZ, (unsigned)DCH2DSIZ);
    printf("    DMA TX (ch3): %s  CHSIRQ=%u(SPI4TX)  cell=%uB  block=%uB\n\r",
           DCH3CONbits.CHEN ? "enabled" : "disabled", (unsigned)DCH3ECONbits.CHSIRQ,
           (unsigned)DCH3CSIZ, (unsigned)DCH3SSIZ);
#endif

    // Chip select GPIO and the VSYNC external interrupt.
    printf("    Chip Select (RD1, GPIO): %s\n\r", nFLIR_VOSPI_CS_PIN ? "deasserted" : "asserted");
    printf("    INT1 (VSYNC/RD0): %s, %s edge, priority %u\n\r",
           getInterruptEnable(external_interrupt_1) ? "enabled" : "disabled",
           INTCONbits.INT1EP ? "rising" : "falling",
           (unsigned)getInterruptPriority(external_interrupt_1));

    terminalTextAttributesReset();
}
